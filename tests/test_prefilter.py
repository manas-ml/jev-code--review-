import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from jev_review.hunk_model import ChangeKind, DiffLine, Hunk
from jev_review.prefilter import prefilter_hunk, prefilter_hunks


def _hunk(file_path, added=("x = 1",), removed=(), change_kind=ChangeKind.MODIFIED):
    lines = [DiffLine("-", t) for t in removed] + [DiffLine("+", t) for t in added]
    return Hunk(
        file_path=file_path,
        change_kind=change_kind,
        header="@@ -1,1 +1,1 @@",
        old_range=(1, 1),
        new_range=(1, 1),
        lines=lines,
    )


def test_lockfile_dropped():
    h = _hunk("package-lock.json")
    result = prefilter_hunk(h)
    assert not result.keep
    assert result.reason == "lockfile"


def test_vendored_path_dropped():
    h = _hunk("third_party/vendor/lib.py")
    result = prefilter_hunk(h)
    assert not result.keep
    assert result.reason == "vendored-path"


def test_generated_marker_dropped():
    h = _hunk("schema.py", added=("# DO NOT EDIT: generated by codegen",))
    result = prefilter_hunk(h)
    assert not result.keep
    assert result.reason == "generated-marker"


def test_whitespace_only_dropped():
    h = _hunk("f.py", added=("x = 1  ",), removed=("x = 1",))
    result = prefilter_hunk(h)
    assert not result.keep
    assert result.reason == "whitespace-only"


def test_mode_only_dropped():
    h = _hunk("script.sh", added=(), removed=(), change_kind=ChangeKind.MODE_ONLY)
    result = prefilter_hunk(h)
    assert not result.keep
    assert result.reason == "no-content-change"


def test_ordinary_python_hunk_kept():
    h = _hunk("app/db/queries.py", added=("query = f'SELECT * FROM t WHERE id = {x}'",), removed=("query = 'SELECT * FROM t WHERE id = %s'",))
    result = prefilter_hunk(h)
    assert result.keep


def test_prefilter_hunks_splits_kept_and_dropped():
    hunks = [
        _hunk("package-lock.json"),
        _hunk("app.py", added=("real_change = True",)),
    ]
    kept, dropped = prefilter_hunks(hunks)
    assert len(kept) == 1
    assert kept[0].file_path == "app.py"
    assert len(dropped) == 1
    assert dropped[0][1] == "lockfile"
