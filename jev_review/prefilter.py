"""Pre-filter stage (design-doc.md §0/§1): drop hunks that never need
review by path or content rules alone, for free — no Jev call. This is
the first stage in the pipeline; anything it doesn't catch still goes
through Jev's own `is_generated_or_lockfile` safety-net question
(design-doc.md §2)."""

from __future__ import annotations

from dataclasses import dataclass

from jev_review.hunk_model import ChangeKind, Hunk

_LOCKFILE_NAMES = {
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "poetry.lock",
    "Pipfile.lock",
    "Cargo.lock",
    "composer.lock",
    "Gemfile.lock",
    "uv.lock",
}

_GENERATED_MARKERS = (
    "do not edit",
    "generated by",
    "@generated",
    "autogenerated",
    "auto-generated",
    "this file is automatically",
)

_VENDOR_PATH_MARKERS = ("/vendor/", "/node_modules/", "/dist/", "/build/", "/.venv/")

_BINARY_EXTENSIONS = {
    ".png", ".jpg", ".jpeg", ".gif", ".pdf", ".zip", ".whl", ".so", ".pyc",
    ".woff", ".woff2", ".ttf", ".ico",
}


@dataclass
class PrefilterResult:
    keep: bool
    reason: str | None = None  # set when keep=False


def _is_lockfile(path: str) -> bool:
    name = path.rsplit("/", 1)[-1]
    return name in _LOCKFILE_NAMES


def _is_vendored(path: str) -> bool:
    p = f"/{path}"
    return any(marker in p for marker in _VENDOR_PATH_MARKERS)


def _is_binary_path(path: str) -> bool:
    return any(path.endswith(ext) for ext in _BINARY_EXTENSIONS)


def _looks_generated(hunk: Hunk) -> bool:
    sample = "\n".join(hunk.added_lines[:5] + hunk.removed_lines[:5]).lower()
    return any(marker in sample for marker in _GENERATED_MARKERS)


def prefilter_hunk(hunk: Hunk) -> PrefilterResult:
    """Return keep=False with a reason for hunks that should never
    reach Jev or the LLM. Everything else is kept (`keep=True`)."""
    if hunk.is_binary or _is_binary_path(hunk.file_path):
        return PrefilterResult(False, "binary-file")
    if hunk.change_kind == ChangeKind.MODE_ONLY:
        return PrefilterResult(False, "no-content-change")
    if _is_lockfile(hunk.file_path):
        return PrefilterResult(False, "lockfile")
    if _is_vendored(hunk.file_path):
        return PrefilterResult(False, "vendored-path")
    if _looks_generated(hunk):
        return PrefilterResult(False, "generated-marker")
    if hunk.is_whitespace_only:
        return PrefilterResult(False, "whitespace-only")
    return PrefilterResult(True, None)


def prefilter_hunks(hunks: list[Hunk]) -> tuple[list[Hunk], list[tuple[Hunk, str]]]:
    """Split hunks into (kept, [(hunk, reason), ...] dropped)."""
    kept: list[Hunk] = []
    dropped: list[tuple[Hunk, str]] = []
    for h in hunks:
        result = prefilter_hunk(h)
        if result.keep:
            kept.append(h)
        else:
            dropped.append((h, result.reason or "unknown"))
    return kept, dropped
